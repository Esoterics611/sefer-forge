#!/usr/bin/env python3
"""Ronnie's meanings of the terms (knowledge/teacher/terms.yaml): check, render, sync.

    python scripts/teacher-terms.py --check     # every `said:` quote found in its file (letters only); slugs resolve
    python scripts/teacher-terms.py             # --check, then write knowledge/teacher/TERMS.md and sync the
                                                # lexicon entries' `teacher:` from it
    python scripts/teacher-terms.py --in <file> # which terms a text uses (by their forms)

terms.yaml keeps apart what Ronnie said (`said:`, his words, checked) and Claude's application of his frame to a
term he has not defined (`applied:`, to confirm or correct). The meaning layer of an explanation (build-biur,
`::: {.meaning}`) draws on it, and prints the terms it uses with this list.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TERMS = ROOT / "knowledge" / "teacher" / "terms.yaml"
OUT = ROOT / "knowledge" / "teacher" / "TERMS.md"
LEX = ROOT / "knowledge" / "lexicon"


def letters(s: str) -> str:
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    s = re.sub(r"[֑-ׇ]", "", s)
    return re.sub(r"[^א-ת]", "", s)


def load() -> dict:
    return yaml.safe_load(TERMS.read_text(encoding="utf-8"))


def all_terms(d: dict) -> list[dict]:
    return (d.get("terms") or []) + (d.get("applied_terms") or [])


def check(d: dict) -> list[str]:
    errs = []
    terms = all_terms(d)
    slugs = {t["slug"] for t in terms}
    cache: dict[str, str] = {}

    def said_ok(items, owner):
        for s in items or []:
            f = ROOT / s["where"]
            if not f.exists():
                errs.append(f"{owner}: file not found: {s['where']}")
                continue
            if s["where"] not in cache:
                cache[s["where"]] = letters(f.read_text(encoding="utf-8"))
            if letters(s["quote"]) not in cache[s["where"]]:
                errs.append(f"{owner}: quote not found in {s['where']}: {s['quote'][:60]!r}")

    p = d.get("principle") or {}
    said_ok(p.get("said"), "principle")
    said_ok(p.get("kavanah_said"), "principle")
    for t in terms:
        said_ok(t.get("said"), t["slug"])
        if "said" not in t and "applied" not in t:
            errs.append(f"{t['slug']}: neither said nor applied")
        if t.get("lexicon") and not (LEX / f"{t['lexicon']}.yaml").exists():
            errs.append(f"{t['slug']}: no lexicon entry {t['lexicon']}")
        for r in t.get("related") or []:
            if r not in slugs:
                errs.append(f"{t['slug']}: related {r!r} is not a term here")
    if len(slugs) != len(terms):
        errs.append("duplicate slugs")
    return errs


def label(where: str) -> str:
    """A reader's label for a file: the shiur it is."""
    m = re.search(r"002-shaar-hayichud/sessions/(\d+)", where)
    if m:
        return f"שער היחוד, שיעור {int(m.group(1))}"
    if "002-shaar-hayichud/introduction" in where:
        return "שער היחוד, הקדמה"
    m = re.search(r"004-levushei-haneshama/sessions/(\d+)", where)
    if m:
        return f"לבושי הנשמה, שיעור {int(m.group(1))}"
    if "004-levushei-haneshama/introduction" in where:
        return "לבושי הנשמה, הקדמה"
    return where


def render(d: dict) -> str:
    out = ["# המושגים כפי שרוני מבאר אותם", "",
           "<!-- Generated by scripts/teacher-terms.py from terms.yaml. Edit terms.yaml and run it again. -->", "",
           "כל מושג בשני ממדים: כמו שהוא בעולמות העליונים (המילון, `knowledge/lexicon/`), וכמו שהוא בנפש האדם "
           "ובעבודה (כאן). **בלשונו**: דבריו, מצוטטים ובדוקים מול השיעור. **יישום**: החלת המסגרת שלו על מושג "
           "שעוד לא ביאר, לאישורו או לתיקונו.", ""]
    p = d.get("principle") or {}
    out += ["## העיקרון", "", p.get("soul", "").strip(), ""]
    for s in (p.get("said") or []) + (p.get("kavanah_said") or []):
        out.append(f"> {s['quote']} — [{label(s['where'])}](../../{s['where']})")
    out += ["", p.get("kavanah", "").strip(), ""]
    out += ["## המושגים, בלשונו", ""]
    for t in d.get("terms") or []:
        out.append(f"### {t['term']}")
        out.append(f"<a id=\"{t['slug']}\"></a>")
        out.append("")
        out.append(t["soul"].strip())
        out.append("")
        for s in t.get("said") or []:
            out.append(f"> {s['quote']} — [{label(s['where'])}](../../{s['where']}) · {s.get('at', '')}")
        if t.get("applied"):
            out += ["", f"**יישום:** {t['applied'].strip()}"]
        extra = []
        if t.get("lexicon"):
            extra.append(f"במילון: [`{t['lexicon']}`](../lexicon/{t['lexicon']}.yaml)")
        if t.get("related"):
            extra.append("ראה גם: " + ", ".join(f"[{r}](#{r})" for r in t["related"]))
        if extra:
            out += ["", " · ".join(extra)]
        out.append("")
    out += ["## יישומים, לאישור", ""]
    for t in d.get("applied_terms") or []:
        out.append(f"### {t['term']}")
        out.append(f"<a id=\"{t['slug']}\"></a>")
        out.append("")
        out.append(f"**יישום:** {t['applied'].strip()}")
        extra = []
        if t.get("lexicon"):
            extra.append(f"במילון: [`{t['lexicon']}`](../lexicon/{t['lexicon']}.yaml)")
        if t.get("related"):
            extra.append("ראה גם: " + ", ".join(f"[{r}](#{r})" for r in t["related"]))
        if extra:
            out += ["", " · ".join(extra)]
        out.append("")
    return "\n".join(out)


def sync_lexicon(d: dict) -> int:
    """Write each term's `said:` into its lexicon entry's `teacher:` (replacing what came from here)."""
    n = 0
    for t in d.get("terms") or []:
        if not t.get("lexicon") or not t.get("said"):
            continue
        p = LEX / f"{t['lexicon']}.yaml"
        text = p.read_text(encoding="utf-8")
        head = text.split("\n", 1)[0] + "\n" if text.startswith("#") else ""
        e = yaml.safe_load(text)
        keep = [x for x in e.get("teacher") or [] if not str(x.get("from", "")).startswith("knowledge/teacher")]
        new = [{"said": s["quote"], "where": s["where"], "from": "knowledge/teacher/terms.yaml"} for s in t["said"]]
        if keep + new != (e.get("teacher") or []):
            e["teacher"] = keep + new
            p.write_text(head + yaml.safe_dump(e, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")
            n += 1
    return n


def uses(d: dict, text: str) -> list[dict]:
    """The terms a text uses, by their forms (whole words, a prefix letter allowed)."""
    found = []
    for t in all_terms(d):
        for f in t.get("forms") or []:
            if re.search(rf"(?<![א-ת])[ובלכמשה]?{re.escape(f)}(?![א-ת])", text):
                found.append(t)
                break
    return found


def main(argv: list[str]) -> int:
    d = load()
    if argv and argv[0] == "--in":
        for t in uses(d, Path(argv[1]).read_text(encoding="utf-8")):
            print(f"{t['slug']}: {t['term']}")
        return 0
    errs = check(d)
    for e in errs:
        print("ERROR:", e)
    n = len(all_terms(d))
    print(f"{n} terms ({len(d.get('terms') or [])} in his words, {len(d.get('applied_terms') or [])} applied): "
          f"{len(errs)} error(s)")
    if errs or (argv and argv[0] == "--check"):
        return 1 if errs else 0
    OUT.write_text(render(d), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}; lexicon entries updated: {sync_lexicon(d)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
