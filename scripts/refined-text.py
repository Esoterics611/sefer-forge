#!/usr/bin/env python3
"""Write a session's refined text: the cleaned transcript with its readability
and style edits applied, for reading before the session is laid out.

Usage:
    python scripts/refined-text.py discourses/004-levushei-haneshama/sessions/001

The cleaned transcript (commentary.md, or transcript.md in a voice-only
discourse) stays what Whisper heard (prompts/transcript-review-rules.md). Its
frontmatter (or, once the session is laid out, its section-plan.yaml) carries
the two refinement passes as exact replacements:
`edits:` (prompts/readability-pass.md: garbled words and broken-off half words
corrected or removed) and `style:` (prompts/style-pass.md: speech made written
Hebrew, every idea kept in its order).

Writes <session>/refined.md: the title, each labelled part (the transcript's
## headings), and the text as it reads after both passes, without the <!-- -->
flags; and, when the passes include the optional teaching pass (`teaching:`,
prompts/teaching-pass.md), refined.teaching.md with it applied. Generated: edit
the transcript's frontmatter and run this again.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

import forgelib as F


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__)
        return 2
    session = Path(argv[0].rstrip("/"))
    src = session / ("transcript.md" if F.voice_only(session) else "commentary.md")
    if not src.exists():
        print(f"{session}: no {src.name} yet")
        return 1
    fm, body, err = F.split_frontmatter(src.read_text(encoding="utf-8"))
    if err:
        print(f"{src}: frontmatter: {err}")
        return 1
    fm = fm or {}
    plan = session / "section-plan.yaml"
    if plan.exists():                     # laid out: the passes live in the plan
        fm = {**fm, **{k: v for k, v in F.load_yaml(plan).items() if k in ("edits", "style", "teaching")}}
    try:
        text, n = F.edit_transcript(body, F.print_edits(fm))
    except F.EditError as e:
        print(f"{src}: {e}")
        return 1
    text = re.sub(r"[ \t]*<!--.*?-->", "", text, flags=re.S)
    text = re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"
    title = fm.get("title") or ""
    head = ["---", yaml.safe_dump({"title": title}, allow_unicode=True, width=10000).strip(), f"built_from: {src.name}",
            f"passes: {F.edit_counts(fm)}", "---", "",
            f"<!-- Generated by scripts/refined-text.py from {src.name} and its frontmatter edits/style. "
            "Edit those and run it again. -->", "", ""]
    (session / "refined.md").write_text("\n".join(head) + text, encoding="utf-8")
    words = len(F.words(text))
    print(f"{session / 'refined.md'}: {F.edit_counts(fm)} applied ({n} replacement(s)); {words} words "
          f"(transcript {len(F.words(body))})")
    variant = session / "refined.teaching.md"          # the optional teaching pass
    if fm.get("teaching"):
        try:
            taught = F.teach_blocks(text, fm["teaching"])
        except F.EditError as e:
            print(f"{src}: {e}")
            return 1
        head[3] = f"passes: {F.edit_counts(fm)}, teaching pass (prompts/teaching-pass.md)"
        head[-3] = (f"<!-- Generated by scripts/refined-text.py: {src.name} with its edits/style and the teaching "
                    "pass (`teaching:`). Edit those and run it again. -->")
        variant.write_text("\n".join(head) + taught, encoding="utf-8")
        print(f"{variant}: the teaching pass; {len(F.words(taught))} words")
    elif variant.exists():
        variant.unlink()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
